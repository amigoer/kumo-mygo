// Command phosphorgen imports a pinned, clean phosphor-icons/core checkout
// into the icons/phosphor (regular weight) and icons/phosphor/fill packages.
// It uses only the standard library. Run from the module root:
//
//	go run ./tools/phosphorgen -upstream ../phosphor-core -commit <40-char sha>
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"go/token"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

type weight struct {
	dir     string // assets/<dir>
	suffix  string // file-name suffix to strip, as "-fill"
	pkg     string // Go package name
	out     string // output directory
	adjunct string // words for doc comments, as "fill weight"
}

var weights = []weight{
	{dir: "regular", pkg: "phosphor", out: "icons/phosphor", adjunct: "regular weight"},
	{dir: "fill", suffix: "-fill", pkg: "fill", out: "icons/phosphor/fill", adjunct: "fill weight"},
}

type icon struct{ name, symbol, svg string }

type provenance struct {
	Repository string `json:"repository"`
	Commit     string `json:"commit"`
	Version    string `json:"version"`
	Weight     string `json:"weight"`
	SHA256     string `json:"inputs_sha256"`
	Count      int    `json:"icon_count"`
}

func main() {
	upstream := flag.String("upstream", "", "path to a clean phosphor-icons/core checkout")
	commit := flag.String("commit", "", "required full upstream commit hash")
	check := flag.Bool("check", false, "verify generated files without writing")
	flag.Parse()
	if err := run(*upstream, *commit, *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func git(dir string, args ...string) (string, error) {
	b, err := exec.Command("git", append([]string{"-C", dir}, args...)...).CombinedOutput()
	if err != nil {
		return "", fmt.Errorf("git: %w: %s", err, b)
	}
	return strings.TrimSpace(string(b)), nil
}

func run(upstream, commit string, check bool) error {
	if upstream == "" || !regexp.MustCompile(`^[0-9a-f]{40}$`).MatchString(commit) {
		return fmt.Errorf("provide -upstream and a full 40-character -commit")
	}
	head, err := git(upstream, "rev-parse", "HEAD")
	if err != nil {
		return err
	}
	if head != commit {
		return fmt.Errorf("checkout is %s, requested %s", head, commit)
	}
	license, err := os.ReadFile(filepath.Join(upstream, "LICENSE"))
	if err != nil {
		return err
	}
	version := ""
	if b, err := os.ReadFile(filepath.Join(upstream, "package.json")); err == nil {
		var pkg struct {
			Version string `json:"version"`
		}
		if json.Unmarshal(b, &pkg) == nil {
			version = pkg.Version
		}
	}
	var catalog [][]icon
	for _, w := range weights {
		icons, sum, err := collect(upstream, w)
		if err != nil {
			return err
		}
		src, err := generate(w, icons)
		if err != nil {
			return err
		}
		prov, _ := json.MarshalIndent(provenance{
			Repository: "https://github.com/phosphor-icons/core",
			Commit:     commit,
			Version:    version,
			Weight:     w.dir,
			SHA256:     sum,
			Count:      len(icons),
		}, "", "  ")
		files := map[string][]byte{
			filepath.Join(w.out, "icons_gen.go"):  src,
			filepath.Join(w.out, "upstream.json"): append(prov, '\n'),
			filepath.Join(w.out, "LICENSE"):       license,
		}
		for path, want := range files {
			if check {
				got, err := os.ReadFile(path)
				if err != nil || !bytes.Equal(got, want) {
					return fmt.Errorf("%s is out of date; run phosphorgen", path)
				}
				continue
			}
			if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
				return err
			}
			if err := os.WriteFile(path, want, 0o644); err != nil {
				return err
			}
		}
		fmt.Printf("%s: %d icons\n", w.out, len(icons))
		catalog = append(catalog, icons)
	}
	src, err := generateCatalog(catalog)
	if err != nil {
		return err
	}
	path := filepath.Join("icons", "phosphor", "catalog", "catalog_gen.go")
	if check {
		got, err := os.ReadFile(path)
		if err != nil || !bytes.Equal(got, src) {
			return fmt.Errorf("%s is out of date; run phosphorgen", path)
		}
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, src, 0o644)
}

// generateCatalog writes the name registry in its own package, so that only
// programs that browse every icon, as the gallery, retain them all.
func generateCatalog(sets [][]icon) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(`// Code generated by phosphorgen; DO NOT EDIT.

// Package catalog lists every Phosphor icon by its upstream kebab-case name.
// Importing it retains the source of every icon, so only catalogs, galleries
// and tests should; applications call the accessors in phosphor and fill.
package catalog

import (
	"github.com/amigoer/kumo-mygo/icons/phosphor"
	"github.com/amigoer/kumo-mygo/icons/phosphor/fill"
	"github.com/egoist/mygo/ui"
)

`)
	for i, name := range []string{"Regular", "Fill"} {
		pkg := []string{"phosphor", "fill"}[i]
		fmt.Fprintf(&b, "// %s maps each %s-weight icon's name to its accessor.\nvar %s = map[string]func() *ui.SVG{\n", name, strings.ToLower(name), name)
		for _, ic := range sets[i] {
			fmt.Fprintf(&b, "\t%q: %s.%s,\n", ic.name, pkg, ic.symbol)
		}
		b.WriteString("}\n\n")
	}
	return format.Source(b.Bytes())
}

func collect(upstream string, w weight) ([]icon, string, error) {
	paths, err := filepath.Glob(filepath.Join(upstream, "assets", w.dir, "*.svg"))
	if err != nil {
		return nil, "", err
	}
	if len(paths) == 0 {
		return nil, "", fmt.Errorf("no icons in assets/%s", w.dir)
	}
	sort.Strings(paths)
	h := sha256.New()
	seen := map[string]string{}
	var icons []icon
	for _, p := range paths {
		b, err := os.ReadFile(p)
		if err != nil {
			return nil, "", err
		}
		h.Write([]byte(filepath.Base(p)))
		h.Write(b)
		name := strings.TrimSuffix(filepath.Base(p), ".svg")
		name = strings.TrimSuffix(name, w.suffix)
		sym := symbol(name)
		if prev, ok := seen[sym]; ok {
			return nil, "", fmt.Errorf("%s and %s both map to %s", prev, name, sym)
		}
		seen[sym] = name
		icons = append(icons, icon{name: name, symbol: sym, svg: strings.TrimSpace(string(b))})
	}
	return icons, hex.EncodeToString(h.Sum(nil)), nil
}

// symbol turns kebab-case into PascalCase; names starting with a digit, or
// colliding with a Go keyword, take the prefix Icon.
func symbol(name string) string {
	var b strings.Builder
	for _, part := range strings.Split(name, "-") {
		if part == "" {
			continue
		}
		b.WriteString(strings.ToUpper(part[:1]) + part[1:])
	}
	s := b.String()
	if s == "" || (s[0] >= '0' && s[0] <= '9') || token.IsKeyword(strings.ToLower(s)) {
		s = "Icon" + s
	}
	return s
}

func generate(w weight, icons []icon) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by phosphorgen; DO NOT EDIT.\n\npackage %s\n\nimport \"github.com/egoist/mygo/ui\"\n", w.pkg)
	for _, ic := range icons {
		fmt.Fprintf(&b, "\n// %s returns the Phosphor %s icon (%s).\nfunc %s() *ui.SVG { return cache%s.get(%s) }\n\nvar cache%s lazyIcon\n",
			ic.symbol, ic.name, w.adjunct, ic.symbol, ic.symbol, strconv.Quote(ic.svg), ic.symbol)
	}
	return format.Source(b.Bytes())
}
